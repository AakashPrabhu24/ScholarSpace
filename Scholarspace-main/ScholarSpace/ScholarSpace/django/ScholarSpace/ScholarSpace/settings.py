def _load_google_oauth_from_secrets_file():
    """Load client_id / client_secret from Google's downloaded JSON."""
    paths = []
    env_path = (os.environ.get('GOOGLE_OAUTH_CLIENT_SECRETS_FILE') or '').strip()
    if env_path:
        paths.append(env_path)
    # Default: copy your client_secret_*.json next to manage.py as this name (no env var needed)
    paths.append(os.path.join(BASE_DIR, 'google_oauth_client_secret.json'))

    for path in paths:
        if not path or not os.path.isfile(path):
            continue
        try:
            with open(path, encoding='utf-8') as f:
                data = json.load(f)
            cfg = data.get('web') or data.get('installed') or {}
            cid = (cfg.get('client_id') or '').strip()
            csec = (cfg.get('client_secret') or '').strip()
            if cid and csec:
                return cid, csec
        except (OSError, json.JSONDecodeError, TypeError, AttributeError):
            continue
    return '', ''


_file_cid, _file_csec = _load_google_oauth_from_secrets_file()
