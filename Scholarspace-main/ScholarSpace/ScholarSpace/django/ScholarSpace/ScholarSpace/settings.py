def _load_google_calendar_api_key():
    """Single-line API key file next to manage.py (gitignored). Env var overrides."""
    path = os.path.join(BASE_DIR, 'google_calendar_api_key.txt')
    if not os.path.isfile(path):
        return ''
    try:
        with open(path, encoding='utf-8') as f:
            return (f.read() or '').strip().splitlines()[0].strip()
    except OSError:
        return ''


